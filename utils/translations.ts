export const useTranslation = (lang: Language) => {
    return (key: keyof typeof translations['es'], params?: Record<string, any>) => {
        const safeLang = lang || 'es';
        const langDict = translations[safeLang] || translations['es'];
        let text = langDict[key] || translations['es'][key] || key;
        if (params) {
            Object.entries(params).forEach(([k, v]) => {
                const regex = new RegExp(`{{${k}}}`, 'g');
                text = text.replace(regex, String(v));
            });
        }
        return text;
    };
};
